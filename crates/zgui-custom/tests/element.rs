//! A custom element, through the real frame loop: measured by its trait, placing its own child.
//!
//! Everything here runs the pipeline a window runs — build, restyle, boxes, layout, fragments —
//! with the registry's sources installed the way the umbrella crate installs them. What is
//! asserted is the two halves of the contract: the element's `layout` answer is what CSS wraps
//! and layout keeps, and a child the element places lands exactly where it put it.

use std::sync::Arc;

use zgui_custom::{CustomElement, CustomLayoutCx, CustomMeasured, ScenePainter};
use zgui_platform::Surface;
use zgui_platform_headless::Harness;
use zgui_runtime::{App, AppError, Runtime};
use zgui_view::{Anchor, BuildCx, IntoView, View};

/// An application whose window records rather than draws, with the custom sources installed.
fn app<V>(css: &str, view: V) -> Harness<Runtime>
where
    V: FnMut(&mut BuildCx<'_>) -> Box<dyn Anchor> + 'static,
{
    let handler = App::new()
        .with_title("custom")
        .with_size(400.0, 300.0)
        .with_stylesheet(css)
        .with_renderer(Box::new(
            |_surface: &Arc<dyn Surface>, target| -> Result<_, AppError> {
                let mut renderer = zgui_testkit_scene::CaptureRenderer::new();
                zgui_render::Renderer::configure(&mut renderer, target);
                Ok(Box::new(renderer) as Box<dyn zgui_render::Renderer>)
            },
        ))
        .with_text_engine(Box::new(|| {
            Box::new(zgui_layout::Paragraphs::new(
                zgui_testkit_scene::MonoShaper::new(),
            ))
        }))
        .with_custom(Box::new(|_document| zgui_custom::sources()))
        .into_handler(view)
        .expect("the reactive runtime installs");
    Harness::new(handler)
}

/// A meter: fixed content size, and its one child parked at a corner of its own choosing.
struct Meter;

impl CustomElement for Meter {
    fn layout(&mut self, cx: &mut CustomLayoutCx<'_>) -> CustomMeasured {
        if cx.final_pass && cx.access.child_count() > 0 {
            cx.access.layout_child(
                0,
                (Some(10.0), Some(6.0)),
                (
                    zgui_custom::Space::Definite(10.0),
                    zgui_custom::Space::Definite(6.0),
                ),
            );
            cx.access.place_child(0, 5.0, 7.0);
        }
        CustomMeasured {
            width: cx.known_width.unwrap_or(40.0),
            height: 24.0,
            ..CustomMeasured::default()
        }
    }

    fn paint(&mut self, painter: &mut ScenePainter<'_>) {
        let size = painter.size();
        painter.fill(
            zgui_geom::Rect::new(
                zgui_geom::Point::new(zgui_geom::DevicePx(0.0), zgui_geom::DevicePx(0.0)),
                size,
            ),
            3.0,
            painter.current_color(),
        );
    }
}

/// The border box of the first box generated by an element named `name`.
fn box_of(window: &zgui_runtime::Window, name: &str) -> Option<(f32, f32, f32, f32)> {
    let document = window.document().borrow();
    let layout = window.layout().borrow();
    for key in layout.keys() {
        let node = layout.node(key);
        let Some(source) = node.source else {
            continue;
        };
        let Some(index) = document.store().index_of(source) else {
            continue;
        };
        if document.store().core(index).local_name().as_str() != name {
            continue;
        }
        let fragment = layout.fragments_of_box(key).first()?;
        let fragment = layout.fragment(*fragment)?;
        return Some((
            fragment.border_box.origin.x.0,
            fragment.border_box.origin.y.0,
            fragment.border_box.size.width.0,
            fragment.border_box.size.height.0,
        ));
    }
    None
}

#[test]
fn a_custom_element_is_measured_by_its_trait_and_places_its_child() {
    let (view, _handle) = zgui_custom::custom(Meter);
    let mut app = app(
        "root { display: block; width: 400px; height: 300px }
         item { display: block }",
        {
            let mut view = Some(view.child(zgui_elements::Element::<Item>::new()));
            move |cx: &mut BuildCx<'_>| {
                Box::new(
                    zgui_elements::r#box()
                        .class("root")
                        .child(view.take().expect("built once"))
                        .into_view()
                        .build(cx),
                )
            }
        },
    );
    app.settle(16);

    let window = &app.app_mut().windows_mut()[0];
    let custom = box_of(window, "custom").expect("the custom element laid out");
    assert_eq!(
        (custom.2, custom.3),
        (400.0, 24.0),
        "block flow stretched the width the shell offered; the height is the element's own answer"
    );
    let item = box_of(window, "item").expect("the child laid out");
    assert_eq!(
        (item.0 - custom.0, item.1 - custom.1),
        (5.0, 7.0),
        "the child sits exactly where the element placed it, relative to the element's box"
    );
    assert_eq!(
        (item.2, item.3),
        (10.0, 6.0),
        "at the size the element laid it out at"
    );
}

/// The custom child's tag, for the fixture: any name will do, the element places by index.
struct Item;

impl zgui_elements::tag::Tag for Item {
    fn name() -> zgui_interned::ElementName {
        zgui_interned::ElementName::new("item")
    }
}

/// A leaf measured at a fixed height of its own.
struct Tall(f32);

impl CustomElement for Tall {
    fn layout(&mut self, cx: &mut CustomLayoutCx<'_>) -> CustomMeasured {
        CustomMeasured {
            width: cx.known_width.unwrap_or(40.0),
            height: self.0,
            ..CustomMeasured::default()
        }
    }

    fn paint(&mut self, _painter: &mut ScenePainter<'_>) {}
}

/// The node of the first element named `name`.
fn node_named(window: &zgui_runtime::Window, name: &str) -> Option<zgui_dom::NodeKey> {
    let document = window.document().borrow();
    let layout = window.layout().borrow();
    layout.keys().into_iter().find_map(|key| {
        let source = layout.node(key).source?;
        let index = document.store().index_of(source)?;
        (document.store().core(index).local_name().as_str() == name).then_some(source)
    })
}

/// A reactive hole that runs again builds the same element type in place: the node stays and its
/// implementation token changes. The box must follow the new implementation.
#[test]
fn a_custom_element_rebuilt_in_place_is_measured_by_its_new_implementation() {
    use zgui_reactive::prelude::{Get, Set};

    let generation = zgui_reactive::RwSignal::new(0u32);
    let mut app = app(
        "root { display: block; width: 400px; height: 300px }",
        move |cx: &mut BuildCx<'_>| {
            let hole = zgui_view::flow::Dynamic::new(move || {
                let height = if generation.get() == 0 { 24.0 } else { 48.0 };
                let (view, _handle) = zgui_custom::custom(Tall(height));
                zgui_view::AnyView::new(view)
            });
            Box::new(
                zgui_elements::r#box()
                    .class("root")
                    .child(hole)
                    .into_view()
                    .build(cx),
            )
        },
    );
    app.settle(16);
    let before = {
        let window = &app.app_mut().windows_mut()[0];
        assert_eq!(box_of(window, "custom").map(|b| b.3), Some(24.0));
        node_named(window, "custom").expect("the custom element")
    };

    generation.set(1);
    app.settle(16);
    let window = &app.app_mut().windows_mut()[0];
    assert_eq!(
        node_named(window, "custom"),
        Some(before),
        "the hole rebuilt the element in place"
    );
    assert_eq!(
        box_of(window, "custom").map(|b| b.3),
        Some(48.0),
        "the box still answers with the old implementation"
    );
}

/// A leaf that records the custom property `--c` each time it is laid out.
struct Reader(std::rc::Rc<std::cell::RefCell<Vec<Option<[f32; 4]>>>>);

impl CustomElement for Reader {
    fn layout(&mut self, cx: &mut CustomLayoutCx<'_>) -> CustomMeasured {
        self.0.borrow_mut().push(
            zgui_css::values::custom::color(cx.style, "c").map(|c| c.to_premultiplied_srgb()),
        );
        CustomMeasured {
            width: cx.known_width.unwrap_or(40.0),
            height: 10.0,
            ..CustomMeasured::default()
        }
    }

    fn paint(&mut self, _painter: &mut ScenePainter<'_>) {}
}

/// An attribute on the custom element's parent moves a custom property the element reads in
/// `layout`; the element is laid out again and reads the new value.
#[test]
fn an_attribute_on_the_parent_reaches_a_custom_property_the_element_reads() {
    use zgui_reactive::prelude::{Get, Set};

    let seen: std::rc::Rc<std::cell::RefCell<Vec<Option<[f32; 4]>>>> = Default::default();
    let held = std::rc::Rc::clone(&seen);
    let variant = zgui_reactive::RwSignal::new("a");
    let mut app = app(
        "root { display: block; width: 400px; height: 300px }
         .r { display: block }
         .r[data-x=a] { --c: rgb(255, 0, 0) }
         .r[data-x=b] { --c: rgb(0, 0, 255) }",
        move |cx: &mut BuildCx<'_>| {
            let (view, _handle) = zgui_custom::custom(Reader(std::rc::Rc::clone(&held)));
            core::mem::forget(_handle);
            Box::new(
                zgui_elements::r#box()
                    .class("r")
                    .attribute(zgui_interned::AttrName::new("data-x"), move || {
                        Some(variant.get().to_owned())
                    })
                    .child(view)
                    .into_view()
                    .build(cx),
            )
        },
    );
    app.settle(16);
    assert_eq!(
        seen.borrow().last().copied().flatten(),
        Some([1.0, 0.0, 0.0, 1.0])
    );

    variant.set("b");
    app.settle(16);
    assert_eq!(
        seen.borrow().last().copied().flatten(),
        Some([0.0, 0.0, 1.0, 1.0]),
        "the element read {:?}",
        seen.borrow()
    );
}

/// The same reader, saying it reads `--c` and nothing else.
struct NarrowReader(std::rc::Rc<std::cell::RefCell<Vec<Option<[f32; 4]>>>>);

impl CustomElement for NarrowReader {
    fn layout(&mut self, cx: &mut CustomLayoutCx<'_>) -> CustomMeasured {
        Reader(std::rc::Rc::clone(&self.0)).layout(cx)
    }

    fn paint(&mut self, _painter: &mut ScenePainter<'_>) {}

    fn custom_properties_read(&self) -> Option<&'static [&'static str]> {
        Some(&["c"])
    }
}

/// An element that names what it reads is laid out again for those names and for no other.
#[test]
fn a_custom_element_that_names_what_it_reads_ignores_other_names() {
    use zgui_reactive::prelude::{Get, Set};

    let seen: std::rc::Rc<std::cell::RefCell<Vec<Option<[f32; 4]>>>> = Default::default();
    let held = std::rc::Rc::clone(&seen);
    let variant = zgui_reactive::RwSignal::new("a");
    let mut app = app(
        "root { display: block; width: 400px; height: 300px }
         .r { display: block; --c: rgb(255, 0, 0) }
         .r[data-x=b] { --u: rgb(0, 255, 0) }
         .r[data-x=c] { --c: rgb(0, 0, 255) }",
        move |cx: &mut BuildCx<'_>| {
            let (view, handle) = zgui_custom::custom(NarrowReader(std::rc::Rc::clone(&held)));
            core::mem::forget(handle);
            Box::new(
                zgui_elements::r#box()
                    .class("r")
                    .attribute(zgui_interned::AttrName::new("data-x"), move || {
                        Some(variant.get().to_owned())
                    })
                    .child(view)
                    .into_view()
                    .build(cx),
            )
        },
    );
    app.settle(16);
    let laid_out = seen.borrow().len();

    variant.set("b");
    app.settle(16);
    assert_eq!(
        seen.borrow().len(),
        laid_out,
        "a name the element does not read moved, and it was not laid out again"
    );

    variant.set("c");
    app.settle(16);
    assert_eq!(
        seen.borrow().last().copied().flatten(),
        Some([0.0, 0.0, 1.0, 1.0])
    );
}
